#!/usr/bin/env node
// Builds Mervin's generated widget files (git-ignored):
//   widget/scripts/content.js   phrases and conversations, compiled from content/
//   widget/scripts/mesh.js      Mervin's skinned mesh, from tools/mesh/ (cached by source hash)
//   widget/scripts/mervin.js    the app (src/) bundled with three.js into one classic script
//
//   node widgets/mervin/build.mjs [--watch] [--skip-mesh] [--lenient]
//   --lenient leaves out content files with problems instead of failing (while writing)

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as esbuild from "esbuild";

const root = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(root, "widget", "scripts");
const args = new Set(process.argv.slice(2));

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return false;
  fs.writeFileSync(file, text);
  return true;
}

async function buildContent() {
  const compiler = path.join(root, "tools", "content-build.mjs");
  const file = path.join(outDir, "content.js");
  if (!fs.existsSync(compiler)) {
    writeIfChanged(file, "window.MERVIN_CONTENT = null;\n");
    return;
  }
  const { compileContent } = await import(pathToFileURL(compiler).href);
  const { script, stats } = compileContent(path.join(root, "content"), { lenient: args.has("--lenient") });
  writeIfChanged(file, script);
  console.log(`  content: ${stats}`);
}

async function buildMesh() {
  const builder = path.join(root, "tools", "mesh", "build-mesh.mjs");
  const file = path.join(outDir, "mesh.js");
  if (!fs.existsSync(builder) || args.has("--skip-mesh")) {
    if (!fs.existsSync(file)) writeIfChanged(file, "window.MERVIN_MESH = null;\n");
    return;
  }
  const hash = crypto.createHash("sha256");
  for (const name of fs.readdirSync(path.dirname(builder)).sort()) {
    hash.update(name);
    hash.update(fs.readFileSync(path.join(path.dirname(builder), name)));
  }
  const digest = hash.digest("hex").slice(0, 16);
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8").startsWith(`// mesh ${digest}`)) {
    console.log("  mesh: cached");
    return;
  }
  const { buildMesh: run } = await import(pathToFileURL(builder).href);
  const started = Date.now();
  const { script, stats } = await run();
  fs.writeFileSync(file, `// mesh ${digest}\n${script}`);
  console.log(`  mesh: ${stats} (${((Date.now() - started) / 1000).toFixed(1)} s)`);
}

const bundleOptions = {
  entryPoints: [path.join(root, "src", "main.js")],
  outfile: path.join(outDir, "mervin.js"),
  bundle: true,
  format: "iife",
  target: "chrome130",
  minify: false,
  legalComments: "eof",
  logLevel: "warning",
  banner: { js: "// Mervin widget. Generated by widgets/mervin/build.mjs from src/; do not edit." },
};

fs.mkdirSync(outDir, { recursive: true });
await buildContent();
await buildMesh();
if (args.has("--watch")) {
  const context = await esbuild.context(bundleOptions);
  await context.watch();
  console.log("  watching src/ ...");
} else {
  const result = await esbuild.build({ ...bundleOptions, metafile: true });
  const bytes = Object.values(result.metafile.outputs)[0].bytes;
  console.log(`  bundle: ${(bytes / 1024).toFixed(0)} KB`);
}
